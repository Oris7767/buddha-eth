#!/usr/bin/env node

/**
 * Generates dist/_redirects post-build as the SINGLE SOURCE OF TRUTH for Netlify redirects.
 * Referencing VedicVN's order of evaluation (First match wins).
 */

import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const distDir = join(__dirname, '..', 'dist');

console.log('\n🔀 [generate-redirects] Generating dist/_redirects for Netlify...');

if (!existsSync(distDir)) {
  console.error(`[ERROR] dist directory not found: ${distDir}`);
  process.exit(1);
}

// Find all pre-rendered post-*.html files
const files = readdirSync(distDir);
const postHtmlFiles = files.filter(f => f.startsWith('post-') && f.endsWith('.html'));

const lines = [
  '# ==========================================================================',
  '# Auto-generated by scripts/generate-redirects.mjs — DO NOT EDIT MANUALLY',
  '# Netlify evaluation order: First match wins',
  '# ==========================================================================',
  '',
  '# Force HTTPS for all requests',
  'http://*    https://:splat    301!',
  '',
  '# Pre-rendered static article pages (200 rewrites for SEO crawlers)'
];

for (const file of postHtmlFiles) {
  const slug = file.replace(/^post-/, '').replace(/\.html$/, '');
  const route = `/post/${slug}`;
  lines.push(`${route.padEnd(45)} /${file}    200`);
}

lines.push('');
lines.push('# Generic post route rewrite to flat file if exists');
lines.push('/post/:slug                                   /post-:slug.html    200');
lines.push('');
lines.push('# SPA fallback (catch-all for React app)');
lines.push('/*                                            /index.html         200');
lines.push('');

const content = lines.join('\n');
const outputPath = join(distDir, '_redirects');
writeFileSync(outputPath, content, 'utf8');

console.log(`  ✅ Written ${lines.length} lines to ${outputPath}`);
console.log('✨ [generate-redirects] Done!\n');
